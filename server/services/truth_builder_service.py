"""
Truth Builder Service
=====================

Processes YouTube video transcripts through Claude AI (subscription SDK)
to build a cumulative "source of truth" document about an AI agency
business model.

Reads video folders from a local directory, processes each one through
Claude, and appends new information to a master truth document.

SDK pattern copied exactly from yt_processor.py._call_via_sdk().
"""

