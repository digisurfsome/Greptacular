async def run_truth_builder(output_dir: Optional[str] = None) -> str:
    """Run the truth builder pipeline as a background task.

    Returns the job_id immediately. The pipeline runs asynchronously
    and updates _state as it progresses.
    """
    if is_running():
        raise RuntimeError("Truth builder is already running")

    job_id = str(uuid.uuid4())[:8]
    _state.reset(job_id)

    # Allow overriding output paths
    truth_doc_path = TRUTH_DOC_PATH
    log_path = LOG_PATH
    if output_dir:
        out = Path(output_dir)
        truth_doc_path = out / "truth_document.md"
        log_path = out / "truth_builder_log.txt"

    # Launch the pipeline as a background task
    asyncio.create_task(_run_pipeline(job_id, truth_doc_path, log_path))
    return job_id


async def _run_pipeline(
    job_id: str,
    truth_doc_path: Path,
    log_path: Path,
) -> None:
    """The actual pipeline loop — runs as an asyncio background task."""
    try:
        _append_log(f"=== Truth Builder started (job {job_id}) ===")

        # Discover video folders
        all_folders = _get_video_folders()
        if not all_folders:
            _state.status = "done"
            _state.progress = "0/0 videos (no video folders found)"
            _append_log("No video folders found. Nothing to process.")
            return

        # Filter out already-processed videos
        processed = _get_processed_videos()
        pending = [f for f in all_folders if f.name not in processed]

        total = len(all_folders)
        already_done = len(processed)
        to_process = len(pending)

        _append_log(f"Found {total} video folders, {already_done} already processed, {to_process} to process")
        _state.progress = f"0/{to_process} videos"

        if to_process == 0:
            _state.status = "done"
            _state.progress = f"{total}/{total} videos (all already processed)"
            _append_log("All videos already processed. Nothing new to do.")
            return

        # Load (or create) the truth document
        truth_doc = _read_truth_doc()

        for i, folder in enumerate(pending, start=1):
            folder_name = folder.name
            _state.progress = f"{i}/{to_process} videos"
            _state.last_video = folder_name
            _append_log(f"Processing [{i}/{to_process}]: {folder_name}")

            try:
                # Read transcript
                transcript_path = folder / "transcript.txt"
                transcript = transcript_path.read_text(encoding="utf-8")

                # Read info.md if it exists
                info_path = folder / "info.md"
                info_text = ""
                if info_path.exists():
                    info_text = info_path.read_text(encoding="utf-8")

                # Build the user message
                user_message = _build_user_message(
                    folder_name=folder_name,
                    transcript=transcript,
                    info_text=info_text,
                    current_truth_doc=truth_doc,
                )

                # Call Claude via subscription SDK
                raw_response = await _call_via_sdk(
                    system_prompt=TRUTH_BUILDER_SYSTEM_PROMPT,
                    user_message=user_message,
                    model=TRUTH_BUILDER_MODEL,
                )

                # Parse the JSON response
                result = _parse_response(raw_response)

                if result.get("has_new_info"):
                    updates = result.get("updates", {})
                    truth_doc = _merge_updates(truth_doc, updates)
                    _save_truth_doc(truth_doc)
                    summary = result.get("video_summary", "")
                    _append_log(f"DONE: {folder_name} | NEW INFO | {summary}")
                else:
                    summary = result.get("video_summary", "")
                    _append_log(f"DONE: {folder_name} | no new info | {summary}")

            except Exception as exc:
                _append_log(f"ERROR: {folder_name} | {exc}")
                logger.exception("Truth builder failed on video: %s", folder_name)
                # Continue with the next video instead of aborting

            # Small delay between videos to avoid rate limiting
            await asyncio.sleep(2)

        _state.status = "done"
        _state.progress = f"{to_process}/{to_process} videos"
        _state.finished_at = time.time()
        elapsed = _state.finished_at - (_state.started_at or _state.finished_at)
        _append_log(f"=== Truth Builder finished (job {job_id}) in {elapsed:.0f}s ===")

    except Exception as exc:
        _state.status = "error"
        _state.error_message = str(exc)
        _append_log(f"FATAL ERROR: {exc}")
        logger.exception("Truth builder pipeline failed")


