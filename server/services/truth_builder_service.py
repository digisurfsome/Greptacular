def _read_log_tail(n: int = 20) -> str:
    """Read the last N lines from the log file."""
    if not LOG_PATH.exists():
        return ""
    try:
        lines = LOG_PATH.read_text(encoding="utf-8").strip().splitlines()
        return "\n".join(lines[-n:])
    except Exception:
        return ""


def _append_log(message: str) -> None:
    """Append a timestamped line to the log file."""
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    line = f"[{timestamp}] {message}\n"
    try:
        OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
        with open(LOG_PATH, "a", encoding="utf-8") as f:
            f.write(line)
    except Exception as exc:
        logger.error("Failed to write to truth builder log: %s", exc)


def _get_processed_videos() -> set[str]:
    """Read the log file and return the set of already-processed video folder names."""
    if not LOG_PATH.exists():
        return set()
    processed = set()
    try:
        for line in LOG_PATH.read_text(encoding="utf-8").splitlines():
            # Lines that mark successful processing contain "DONE:"
            if "DONE:" in line:
                # Format: [timestamp] DONE: folder_name
                parts = line.split("DONE:", 1)
                if len(parts) == 2:
                    folder_name = parts[1].strip()
                    if folder_name:
                        processed.add(folder_name)
    except Exception:
        pass
    return processed


def _get_video_folders() -> list[Path]:
    """Get video folders sorted by modification time (oldest first).

    Each valid folder must contain a transcript.txt file.
    """
    if not VIDEOS_DIR.exists():
        return []
    folders = []
    for entry in sorted(VIDEOS_DIR.iterdir()):
        if entry.is_dir() and (entry / "transcript.txt").exists():
            folders.append(entry)
    # Sort by modification time (oldest first)
    folders.sort(key=lambda p: p.stat().st_mtime)
    return folders


def _read_truth_doc() -> str:
    """Read the current truth document, creating it from template if missing."""
    if TRUTH_DOC_PATH.exists():
        return TRUTH_DOC_PATH.read_text(encoding="utf-8")
    # Create initial document from template
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    TRUTH_DOC_PATH.write_text(TRUTH_DOC_TEMPLATE, encoding="utf-8")
    return TRUTH_DOC_TEMPLATE


def _save_truth_doc(content: str) -> None:
    """Save the truth document to disk."""
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    TRUTH_DOC_PATH.write_text(content, encoding="utf-8")


def _merge_updates(truth_doc: str, updates: dict) -> str:
    """Merge new section updates into the truth document.

    For each section that has new text, append it under the matching
    ## header in the document.
    """
    for section_name, new_text in updates.items():
        if not new_text or new_text == "null" or str(new_text).strip().lower() == "null":
            continue
        header = f"## {section_name}"
        if header not in truth_doc:
            # Section header missing — append it at the end
            truth_doc += f"\n{header}\n\n{new_text}\n"
        else:
            # Find the header and append after it (before the next ## or end)
            idx = truth_doc.index(header)
            # Find the end of the header line
            header_end = truth_doc.index("\n", idx) if "\n" in truth_doc[idx:] else len(truth_doc)
            # Find the next ## header (or end of document)
            next_header_idx = len(truth_doc)
            for other_header in SECTION_HEADERS:
                marker = f"\n## {other_header}"
                pos = truth_doc.find(marker, header_end)
                if pos >= 0 and pos < next_header_idx:
                    next_header_idx = pos
            # Insert the new text before the next section
            insertion_point = next_header_idx
            new_block = f"\n{new_text.strip()}\n"
            truth_doc = truth_doc[:insertion_point] + new_block + truth_doc[insertion_point:]
    return truth_doc


