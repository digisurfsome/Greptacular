async def _call_via_sdk(
    system_prompt: str,
    user_message: str,
    model: str,
    timeout: float | None = None,
) -> str:
    """Call Claude via the Agent SDK using SUBSCRIPTION auth ONLY.

    Uses ``ClaudeSDKClient`` with ``force_subscription=True`` — clears
    API key so the CLI falls back to ``~/.claude/.credentials.json``
    (subscription OAuth).  NO API CREDITS BURNED.

    IMPORTANT: Uses ``permission_mode="acceptEdits"`` to match ALL
    working SDK clients in this codebase.

    AGENTS: DO NOT add an API key fallback here.
    """
    from claude_agent_sdk import ClaudeAgentOptions, ClaudeSDKClient

    from registry import get_effective_sdk_env

    t0 = time.time()

    # CRITICAL: Remove CLAUDECODE env var — it blocks nested Claude CLI sessions.
    os.environ.pop("CLAUDECODE", None)

    system_cli = shutil.which("claude")
    if not system_cli:
        raise RuntimeError("Claude CLI not found on PATH")
    logger.info("[truth-builder SDK] CLI binary: %s", system_cli)

    sdk_env = get_effective_sdk_env(force_subscription=True)
    sdk_env.pop("CLAUDECODE", None)

    # Subscription verification
    api_key_val = sdk_env.get("ANTHROPIC_API_KEY", "(NOT SET)")
    has_api_key = bool(api_key_val and api_key_val not in ("", "(NOT SET)"))
    if has_api_key:
        logger.warning("[truth-builder SDK] API key present despite force_subscription=True!")

    t1 = time.time()
    logger.info("[truth-builder SDK] Auth setup: %.1fs", t1 - t0)

    # Use a temp directory as cwd
    scratch = tempfile.mkdtemp(prefix="truth_builder_")

    # Create settings file matching the working pattern
    import pathlib as _pl
    settings_file = _pl.Path(scratch) / ".claude-truth-settings.json"
    settings_file.write_text(json.dumps({
        "permissions": {
            "defaultMode": "acceptEdits",
            "allow": [],
        },
    }))

    client = ClaudeSDKClient(
        options=ClaudeAgentOptions(
            model=model,
            cli_path=system_cli,
            system_prompt=system_prompt,
            env=sdk_env,
            max_turns=2,
            permission_mode="acceptEdits",
            allowed_tools=[],
            cwd=scratch,
            settings=str(settings_file.resolve()),
            setting_sources=["user"],
        )
    )

    t2 = time.time()
    logger.info(
        "[truth-builder SDK] Client created: %.1fs | model=%s | mode=acceptEdits",
        t2 - t1, model,
    )

    effective_timeout = timeout if timeout is not None else SDK_TIMEOUT_SECONDS
    logger.info(
        "[truth-builder SDK] Timeout: %ss | Payload: %s chars",
        effective_timeout, f"{len(user_message):,}",
    )

    async def _run_sdk() -> str:
        sdk_t0 = time.time()
        logger.info("[truth-builder SDK] Spawning CLI subprocess...")

        try:
            await client.__aenter__()
        except Exception as enter_err:
            err_str = str(enter_err)
            logger.error("[truth-builder SDK] CLI FAILED TO START: %s", err_str)
            raise RuntimeError(
                f"Claude CLI failed to start (model={model}): {err_str}"
            ) from enter_err

        sdk_t1 = time.time()
        logger.info("[truth-builder SDK] CLI subprocess ready: %.1fs", sdk_t1 - sdk_t0)

        logger.info("[truth-builder SDK] Sending query (%s chars)...", f"{len(user_message):,}")
        await client.query(user_message)
        sdk_t2 = time.time()
        logger.info(
            "[truth-builder SDK] Query sent: %.1fs — now waiting for %s to respond...",
            sdk_t2 - sdk_t1, model,
        )

        full_text = ""
        msg_count = 0
        sdk_error: str | None = None
        rate_limit_count = 0

        # The SDK may THROW "Unknown message type: rate_limit_event"
        # instead of yielding it.  If we already have content, catch
        # the exception and use what we collected.
        try:
            async for msg in client.receive_response():
                msg_type = type(msg).__name__
                msg_count += 1

                if msg_type in ("RateLimitEvent", "rate_limit_event"):
                    rate_limit_count += 1
                    logger.warning("[truth-builder SDK] Rate limit #%d", rate_limit_count)
                    continue

                elif msg_type == "AssistantMessage" and hasattr(msg, "content"):
                    for block in msg.content:
                        block_type = type(block).__name__
                        if block_type == "TextBlock" and hasattr(block, "text"):
                            full_text += block.text

                elif msg_type == "ResultMessage":
                    is_error = getattr(msg, "is_error", False)
                    if is_error:
                        result_text = ""
                        if hasattr(msg, "result") and msg.result:
                            result_text = str(msg.result)[:500]
                        elif hasattr(msg, "content"):
                            for block in getattr(msg, "content", []):
                                if hasattr(block, "text"):
                                    result_text += block.text
                        sdk_error = f"SDK error (model={model}): {result_text}" if result_text else f"SDK ResultMessage error (model={model})"
                        logger.error("[truth-builder SDK] ERROR: %s", sdk_error)
                    else:
                        logger.info("[truth-builder SDK] DONE | %s chars total", f"{len(full_text):,}")

        except Exception as stream_exc:
            exc_str = str(stream_exc)
            logger.warning("[truth-builder SDK] Stream exception: %s", exc_str)
            if full_text.strip() and "unknown message type" in exc_str.lower():
                logger.info("[truth-builder SDK] Recovered: using %s chars despite SDK error", f"{len(full_text):,}")
            elif full_text.strip():
                logger.warning("[truth-builder SDK] Stream error after receiving %s chars", f"{len(full_text):,}")
            else:
                raise

        if sdk_error:
            raise RuntimeError(sdk_error)

        if not full_text.strip():
            raise RuntimeError(
                f"Claude SDK returned empty response. "
                f"Messages: {msg_count}, Rate limits: {rate_limit_count}"
            )
        return full_text.strip()

    try:
        return await asyncio.wait_for(_run_sdk(), timeout=effective_timeout)
    except asyncio.TimeoutError:
        elapsed = time.time() - t0
        logger.error("[truth-builder SDK] TIMEOUT after %.0fs (limit: %ss)", elapsed, effective_timeout)
        raise RuntimeError(
            f"Claude SDK timed out after {effective_timeout}s. Try again."
        )
    finally:
        try:
            await client.__aexit__(None, None, None)
        except Exception:
            pass
        try:
            shutil.rmtree(scratch, ignore_errors=True)
        except Exception:
            pass


