def _build_user_message(
    folder_name: str,
    transcript: str,
    info_text: str,
    current_truth_doc: str,
) -> str:
    """Build the user message for Claude with the video data and current truth doc."""
    parts = []

    parts.append(f"## Video: {folder_name}")

    if info_text:
        parts.append(f"## Video Info\n{info_text}")

    parts.append(f"## Transcript\n{transcript}")

    # Include the current truth doc so Claude knows what's already captured
    parts.append(f"## Current Truth Document\n{current_truth_doc}")

    return "\n\n".join(parts)


def _parse_response(raw_text: str) -> dict:
    """Parse the JSON response from Claude.

    Handles common LLM output issues: markdown fences, preamble text,
    trailing commentary.
    """
    text = raw_text.strip()

    # Try direct parse
    try:
        return json.loads(text)
    except (json.JSONDecodeError, ValueError):
        pass

    # Strip markdown code fences
    import re
    if "```" in text:
        fence_match = re.search(r"```(?:json)?\s*\n?(.*?)```", text, re.DOTALL)
        if fence_match:
            fenced = fence_match.group(1).strip()
            try:
                return json.loads(fenced)
            except (json.JSONDecodeError, ValueError):
                pass

    # Extract first balanced JSON object
    first_brace = text.find("{")
    last_brace = text.rfind("}")
    if first_brace >= 0 and last_brace > first_brace:
        candidate = text[first_brace:last_brace + 1]
        try:
            return json.loads(candidate)
        except (json.JSONDecodeError, ValueError):
            pass

    # If all parsing fails, return a safe fallback
    logger.error("Failed to parse truth builder response. Raw text:\n%s", text[:1000])
    return {"has_new_info": False, "updates": {}, "video_summary": "Parse error — skipped"}
