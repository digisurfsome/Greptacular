# Singleton job state (no database — just in-memory + file-based)
# ---------------------------------------------------------------------------

class _JobState:
    """In-memory state for the currently running (or last completed) job."""

    def __init__(self) -> None:
        self.status: str = "idle"  # idle | running | done | error
        self.job_id: Optional[str] = None
        self.progress: str = ""
        self.last_video: str = ""
        self.error_message: str = ""
        self.started_at: Optional[float] = None
        self.finished_at: Optional[float] = None

    def reset(self, job_id: str) -> None:
        self.status = "running"
        self.job_id = job_id
        self.progress = "0/0 videos"
        self.last_video = ""
        self.error_message = ""
        self.started_at = time.time()
        self.finished_at = None


_state = _JobState()


def get_job_state() -> dict:
    """Return the current job state as a plain dict for the status endpoint."""
    log_tail = _read_log_tail(20)
    return {
        "status": _state.status,
        "job_id": _state.job_id,
        "progress": _state.progress,
        "last_video": _state.last_video,
        "error_message": _state.error_message,
        "log_tail": log_tail,
    }


def get_truth_document() -> str:
    """Return the truth document content, or empty string if it doesn't exist."""
    if TRUTH_DOC_PATH.exists():
        return TRUTH_DOC_PATH.read_text(encoding="utf-8")
    return ""


def is_running() -> bool:
    """Check if a job is currently running."""
    return _state.status == "running"


